import os
import random
import struct
import sys

import analyze
import emit
import ppc
import rpx

BRANCHES = {"b", "bc", "bclr", "bcctr", "sc", "rfi", "tw", "twi", "mftb", "mfmsr", "mtmsr", "mcrxr", "lswx", "stswx",
            "mffs", "mtfsf", "mtfsb0", "mtfsb1", "mtfsfi", "mcrfs", "fsqrt", "fsqrts", "fctiw", "lwarx", "stwcx."}

class OneImg:
    def __init__(self, word, addr):
        self.w, self.a = word, addr
        self.switch_tables = {}
        self.rel24 = {}

    def insn(self, a):
        return ppc.decode(self.w, a)

    def branch_target(self, i):
        return i.target

class Ctx:
    def __init__(self, img):
        self.img = img

    def func_name(self, a):
        return None

    def import_slot(self, a):
        return None

def main():
    path = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "generated", "interptest.cpp")
    count = int(sys.argv[3]) if len(sys.argv) > 3 else 4000
    r = rpx.load(path)
    text = next(s for s in r.sections if s.name == ".text")
    words = {}
    for o in range(0, len(text.data), 4):
        w = struct.unpack_from(">I", text.data, o)[0]
        i = ppc.decode(w)
        if i is None or i.op in BRANCHES or i.op.endswith("o"):
            continue
        words.setdefault(i.op, set()).add(w)
    rng = random.Random(1)
    chosen = []
    per = max(8, count // max(1, len(words)))
    for op, ws in sorted(words.items()):
        ws = sorted(ws)
        rng.shuffle(ws)
        chosen += ws[:per]
    lines = ["// Generated by tools/recomp/test_interp.py", "#include <cmath>", "#include <cstdio>", "#include <cstdlib>",
             "#include <cstring>", "#include <random>", "#include <vector>", '#include "wf/ppc.h"', '#include "cpu/interp.h"', '#include "core/log.h"', "#include <cstddef>", ""]
    funcs, kept = [], []
    for n, w in enumerate(chosen):
        i = ppc.decode(w, 0x02000000)
        if i.op in ("lwz", "lbz", "lhz", "lha", "stw", "stb", "sth", "lfs", "lfd", "stfs", "stfd", "lmw", "stmw") and i.ra == 0:
            continue
        f = analyze.Function(0x02000000)
        f.insns = [0x02000000]
        em = emit.FunctionEmitter(Ctx(OneImg(w, 0x02000000)))
        try:
            body = em.function(f, f"t_{n}")
        except emit.EmitError:
            continue
        body = [l for l in body if "PPC_INTERP_ENTRY" not in l]
        lines += body
        memop = emit.FunctionEmitter(Ctx(OneImg(w, 0x02000000))).memop(i) is not None or i.op in ("dcbz", "dcbz_l") or i.op.startswith("psq")
        funcs.append(f"{{0x{w:08X}u, t_{n}, {'true' if memop else 'false'}}}")
        kept.append(i.op)
    lines.append("struct Case { uint32_t word; wf::PPCFunc* fn; bool mem; };")
    lines.append(f"static const Case kCases[] = {{{', '.join(funcs)}}};")
    lines.append(r'''
constexpr uint32_t kMem = 0x400000, kPc = 0x1000;
static void randomize(wf::PPCContext& c, std::vector<uint8_t>& mem, std::mt19937& g, bool memop)
{
    for (size_t i = 0; i < mem.size(); i += 4) { uint32_t v = g(); std::memcpy(&mem[i], &v, 4); }
    for (int k = 0; k < 32; k++) c.r[k] = 0x100000 + (g() % 0x100000 & ~7u);
    if (!memop)
        for (int k = 0; k < 32; k++) if (g() & 1) c.r[k] = (g() & 3) ? g() : (g() & 0xFF);  // arbitrary values
    for (int k = 0; k < 32; k++)
    {
        float a = (float)((int)(g() % 2000000) - 1000000) / 997.0f, b = (float)((int)(g() % 2000) - 1000) / 7.0f;
        c.f[k].ps0 = (g() & 3) ? (double)a : (double)a * 1.0000001;
        c.f[k].ps1 = b;
    }
    for (int k = 0; k < 32; k++) c.cr[k] = g() & 1;
    c.xer_ca = g() & 1; c.xer_so = 0; c.xer_ov = 0; c.xer_bc = 0;
    c.lr = g(); c.ctr = g() % 64;
    static const uint32_t types[] = {0, 4, 5, 6, 7};
    for (int k = 0; k < 8; k++)
        c.gqr[k] = types[g() % 5] | ((g() % 8) << 8) | (types[g() % 5] << 16) | ((g() % 8) << 24);
}
static bool same(const wf::PPCContext& a, const wf::PPCContext& b)
{
    if (memcmp(a.r, b.r, sizeof a.r) || a.lr != b.lr || a.ctr != b.ctr || memcmp(a.cr, b.cr, 32) || a.xer_ca != b.xer_ca ||
        a.xer_so != b.xer_so || memcmp(a.gqr, b.gqr, sizeof a.gqr))
        return false;
    for (int k = 0; k < 32; k++)
        if (a.f[k].ps0u != b.f[k].ps0u || a.f[k].ps1u != b.f[k].ps1u) return false;
    return true;
}
namespace wf {
PPCFunc** g_funcTable;
void bad_indirect_call(PPCContext&, uint32_t t, uint32_t f) { std::printf("bad call %08X from %08X\n", t, f); std::abort(); }
void yield(PPCContext&, uint8_t*) {}
void trap(PPCContext&, uint8_t*, uint32_t) { std::abort(); }
void call_import(PPCContext&, uint8_t*, uint32_t) { std::abort(); }
void fatal_message(std::string_view m) { std::printf("fatal: %.*s\n", (int)m.size(), m.data()); std::exit(2); }
void log_write(LogLevel, std::string_view, std::string_view) {}
namespace game_module { void set_interp_active(bool) {} }
}
int main()
{
    std::mt19937 g(7);
    int fail = 0, n = (int)(sizeof kCases / sizeof kCases[0]);
    std::vector<uint8_t> m1(kMem + 64), m2(kMem + 64);
    for (const Case& k : kCases)
        for (int rep = 0; rep < 6; rep++)
        {
            static wf::PPCContext c1, c2;
            randomize(c1, m1, g, k.mem);
            c2.yield_request = 0; c1.yield_request = 0;
            std::memcpy((void*)&c2, (void*)&c1, offsetof(wf::PPCContext, yield_request));
            m2 = m1;
            wf::st32(m2.data(), kPc, k.word);
            wf::st32(m2.data(), kPc + 4, 0x4E800020u);  // blr
            wf::st32(m1.data(), kPc, k.word);
            wf::st32(m1.data(), kPc + 4, 0x4E800020u);
            uint32_t lr = c1.lr;
            k.fn(c1, m1.data());
            wf::interp::call(c2, m2.data(), kPc);
            c2.lr = c2.lr == lr ? c2.lr : c2.lr;
            if (!same(c1, c2) || m1 != m2)
            {
                if (fail < 40) std::printf("MISMATCH %08X (rep %d)\n", k.word, rep);
                fail++;
                break;
            }
        }
    std::printf("%d instructions, %d mismatched\n", n, fail);
    return fail != 0;
}
''')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    ops = sorted(set(kept))
    print(f"wrote {len(funcs)} instructions ({len(ops)} kinds) to {out}")

if __name__ == "__main__":
    main()
