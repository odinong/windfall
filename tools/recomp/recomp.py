import argparse
import hashlib
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze
import emit
import layout
import module_glue
import rpx

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

def load_hooks(path, wrapped=None):
    hooks = {}
    if not os.path.exists(path):
        return hooks
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        addr, name = int(parts[0], 16), parts[1]
        hooks[addr] = name
        if wrapped is not None and len(parts) > 2 and parts[2] == "wrap":
            wrapped.add(addr)
    return hooks

class Context:
    def __init__(self, img, funcs, hooks, imports_by_addr):
        self.img = img
        self.funcs = funcs
        self.hooks = hooks
        self.imports_by_addr = imports_by_addr

    def func_name(self, addr):
        if addr in self.hooks:
            return self.hooks[addr]
        if addr in self.funcs:
            return f"sub_{addr:08X}"
        return None

    def import_slot(self, addr):
        return self.imports_by_addr.get(addr)

def write_if_changed(path, text):
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return False
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return True

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rpx", nargs="?")
    ap.add_argument("--out", default=os.path.join(ROOT, "generated"))
    ap.add_argument("--shard-insns", type=int, default=12000)
    ap.add_argument("--build-id", action="store_true", help="print the recompiler's build id and exit")
    a = ap.parse_args()
    if a.build_id:
        print(module_glue.build_id())
        return 0
    if not a.rpx:
        ap.error("the path to cking.rpx is required")
    t0 = time.time()

    game = json.load(open(os.path.join(ROOT, "config", "game.json")))
    sha1 = hashlib.sha1(open(a.rpx, "rb").read()).hexdigest()
    if sha1 != game["sha1"]["code/cking.rpx"]:
        sys.exit(f"cking.rpx SHA-1 {sha1} does not match the supported revision ({game['product_code']} v{game['title_version']})")

    r = rpx.load(a.rpx)
    slots, imports_by_addr = layout.assign_imports(r)
    img = analyze.Image(r)
    mism = layout.relocate_words(r, img.text, img.words, imports_by_addr)
    img._dec.clear()
    print(f"relocated .text; {mism} non-import relocations differed from the pre-linked file")

    wrapped = set()
    hooks = load_hooks(os.path.join(ROOT, "config", "hooks.txt"), wrapped)
    probes = load_hooks(os.path.join(ROOT, "config", "probes.txt"))
    funcs = analyze.discover(img, extra_seeds=hooks.keys())
    ctx = Context(img, funcs, hooks, imports_by_addr)
    ctx.probes = probes
    em = emit.FunctionEmitter(ctx)

    os.makedirs(a.out, exist_ok=True)
    starts = sorted(funcs)
    shards, cur, cur_n = [], [], 0
    for s in starts:
        cur.append(s)
        cur_n += len(funcs[s].insns)
        if cur_n >= a.shard_insns:
            shards.append(cur)
            cur, cur_n = [], 0
    if cur:
        shards.append(cur)

    files = []
    errors = 0
    for n, shard in enumerate(shards):
        bodies, callees, defined = [], set(), set()
        for s in shard:
            if s in hooks and s not in wrapped:
                continue
            name = f"sub_{s:08X}" + ("_orig" if s in hooks else "")
            try:
                bodies.append("\n".join(em.function(funcs[s], name)))
            except emit.EmitError as e:
                errors += 1
                print(f"error in {name}: {e}")
                bodies.append(f"PPC_FUNC({name}) {{ wf::trap(ctx, base, {emit.h(s)}); }} // recompile error: {e}")
            callees |= em.callees
            defined.add(name)
        decls = "\n".join(f"PPC_FUNC({c});" for c in sorted(callees | defined))
        text = f'// Generated by tools/recomp/recomp.py. Do not edit or commit.\n#include "wf/ppc.h"\n\n{decls}\n\n' + "\n\n".join(bodies) + "\n"
        fn = f"recomp_{n:03d}.cpp"
        write_if_changed(os.path.join(a.out, fn), text)
        files.append(fn)

    names = [ctx.func_name(s) for s in starts]
    decls = "\n".join(f"PPC_FUNC({n});" for n in names)
    thunks = [s for s in slots if s.is_func]
    thunk_defs = "\n".join(f"static PPC_FUNC(imp_{s.id}) {{ wf::call_import(ctx, base, {s.id}); }}" for s in thunks)
    maps = ",\n".join(f"\t{{0x{s:08X}, {n}}}" for s, n in zip(starts, names))
    tmaps = ",\n".join(f"\t{{0x{s.guest:08X}, imp_{s.id}}}" for s in thunks)
    write_if_changed(os.path.join(a.out, "recomp_table.cpp"),
                     f'// Generated. Do not edit or commit.\n#include "wf/ppc.h"\n#include "wf/recomp_api.h"\n\n{decls}\n\n{thunk_defs}\n\n'
                     f"const wf::FuncMapping wf::g_funcMappings[] = {{\n{maps},\n{tmaps},\n\t{{0, nullptr}}\n}};\n")
    files.append("recomp_table.cpp")

    imp_rows = ",\n".join(f'\t{{{s.id}, "{s.module}", "{s.name}", {str(s.is_func).lower()}, 0x{s.guest:08X}}}' for s in slots)
    fi = r.fileinfo
    write_if_changed(os.path.join(a.out, "recomp_imports.cpp"),
                     f'// Generated. Do not edit or commit.\n#include "wf/recomp_api.h"\n\n'
                     f"const wf::ImportInfo wf::g_imports[] = {{\n{imp_rows}\n}};\n"
                     f"const uint32_t wf::g_importCount = {len(slots)};\n"
                     f'const wf::ImageInfo wf::g_image = {{0x{r.entry:08X}, 0x{fi["sdaBase"]:08X}, 0x{fi["sda2Base"]:08X}, 0x{fi["stackSize"]:X}, "{sha1}"}};\n')
    files.append("recomp_imports.cpp")

    write_if_changed(os.path.join(a.out, "recomp_module.cpp"), module_glue.module_glue(hooks, wrapped))
    files.append("recomp_module.cpp")

    write_if_changed(os.path.join(a.out, "sources.cmake"),
                     "set(WF_GENERATED_SOURCES\n" + "\n".join(f"  ${{CMAKE_CURRENT_LIST_DIR}}/{f}" for f in files) + "\n)\n")

    for w in em.warnings[:20]:
        print("warning:", w)
    total = sum(len(f.insns) for f in funcs.values())
    print(f"{len(funcs)} functions, {total} instructions, {len(shards)} shards, {len(em.warnings)} warnings, "
          f"{errors} errors, {time.time() - t0:.0f}s")
    return 1 if errors else 0

if __name__ == "__main__":
    sys.exit(main())
